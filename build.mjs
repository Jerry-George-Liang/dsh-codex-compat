import { readFile, writeFile } from 'node:fs/promises';
import assert from 'node:assert/strict';

const root = new URL('./', import.meta.url);
const pkg = JSON.parse(await readFile(new URL('package.json', root), 'utf8'));
assert.match(pkg.version, /^\d+\.\d+\.\d+$/);
// A versioned, self-contained Host entry prevents installed-package ESM caches
// from retaining an older controller after remove/install in the same process.
const inputs = [
  ['compat.js', []],
  ['controller.js', ["import { createCompatibilityServer } from './compat.js';\n"]],
  ['task-scope.js', []],
  ['index.js', [
    "import { createTaskScope } from './task-scope.js';\n",
    "import { addCompatibilityHeaders, defaults, matchesRequest, prepareConfig } from './compat.js';\n",
    "import { ModeController } from './controller.js';\n",
  ]],
];
const sections = [];
for (const [file, imports] of inputs) {
  // Git's core.autocrlf can produce CRLF checkouts on Windows.
  let text = (await readFile(new URL(file, root), 'utf8')).replace(/\r\n/g, '\n');
  for (const line of imports) {
    assert.equal(text.split(line).length, 2, `Expected exactly one local import in ${file}`);
    text = text.replace(line, '');
  }
  sections.push(`// Source: ${file}\n${text}`);
}
const entry = `./host-${pkg.version}.js`;
assert.equal(pkg.exports['.'], entry, 'Package export must match the versioned Host entry');
await writeFile(new URL(entry, root), `// Generated by build.mjs; edit the source modules.\n${sections.join('\n')}`);
